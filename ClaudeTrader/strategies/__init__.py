class HybridStrategy(BaseStrategy):
    """
    Hybrid Strategy

    Combines multiple strategies with ensemble logic.
    """

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.strategies = [
            SuperTrendStrategy(config),
            MultiFactorStrategy(config)
        ]

    def generate_signal(self, market_data: Dict[str, Any]) -> Optional[StrategySignal]:
        """Generate signal from ensemble of strategies"""

        # Get signals from all strategies
        signals = []
        for strategy in self.strategies:
            signal = strategy.generate_signal(market_data)
            if signal:
                signals.append(signal)

        if not signals:
            return None

        # Ensemble logic: majority vote weighted by confidence
        buy_score = sum(s.confidence for s in signals if s.action == 'buy')
        sell_score = sum(s.confidence for s in signals if s.action == 'sell')
        hold_score = sum(s.confidence for s in signals if s.action == 'hold')

        max_score = max(buy_score, sell_score, hold_score)

        if max_score == buy_score:
            action = 'buy'
        elif max_score == sell_score:
            action = 'sell'
        else:
            action = 'hold'

        return StrategySignal(
            action=action,
            confidence=max_score / len(signals),
            price=market_data.get('close', [0])[-1],
            timestamp=datetime.now(),
            indicators={'ensemble_score': max_score},
            reasoning=f"Ensemble decision from {len(signals)} strategies"
        )

    def backtest(self, symbol: str, period: str) -> Dict[str, Any]:
        """Backtest hybrid strategy using the event-driven engine."""
        return _run_backtest(self, symbol, period, self.config)


# Strategy registry
STRATEGY_REGISTRY = {
    'supertrend': SuperTrendStrategy,
    'rl_agent': RLStrategy,
    'multi_factor': MultiFactorStrategy,
    'hybrid': HybridStrategy
}


def get_strategy(strategy_name: str, config: Dict[str, Any]) -> BaseStrategy:
    """Factory function to get strategy instance"""

    strategy_class = STRATEGY_REGISTRY.get(strategy_name)

    if strategy_class is None:
        raise ValueError(f"Unknown strategy: {strategy_name}")

    return strategy_class(config)


def list_strategies() -> List[str]:
    """List available strategies"""
    return list(STRATEGY_REGISTRY.keys())


