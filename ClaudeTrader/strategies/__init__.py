def _run_backtest(
    strategy: "BaseStrategy",
    symbol: str,
    period: str,
    config: Dict[str, Any],
) -> Dict[str, Any]:
    """Run the event-driven backtester for a strategy over historical data.

    Fetches OHLCV data for ``symbol`` and replays it through
    :func:`utils.backtest.backtest_strategy`, returning a serializable summary
    that includes the full performance report. Imports are done lazily to avoid
    import cycles and keep optional dependencies isolated.
    """
    try:
        from utils.backtest import backtest_strategy
        from utils.data_fetcher import fetch_market_data
        from utils.performance import periods_per_year_for

        limit = _period_to_bars(period)
        timeframe = config.get('trading', {}).get('default_timeframe', '1h')
        market_data = fetch_market_data(symbol, timeframe, limit=limit)

        if not market_data or not market_data.get('close'):
            return {
                'strategy': strategy.name,
                'symbol': symbol,
                'period': period,
                'error': 'No market data available for backtest',
            }

        bt_config = dict(config.get('backtesting', {}))
        bt_config.setdefault('periods_per_year', periods_per_year_for(timeframe))
        # Inherit risk parameters from the strategy where available.
        bt_config.setdefault('atr_period', strategy.parameters.get('atr_period', 14))

        result = backtest_strategy(strategy, market_data, bt_config)
        result.update({'strategy': strategy.name, 'symbol': symbol, 'period': period})
        # Keep the equity curve out of the lightweight summary for readability.
        result.pop('equity_curve', None)
        return result

    except Exception as e:  # pragma: no cover - defensive
        logger.error(f"Backtest failed for {strategy.name} on {symbol}: {e}")
        return {
            'strategy': strategy.name,
            'symbol': symbol,
            'period': period,
            'error': str(e),
        }


def _period_to_bars(period: str, default: int = 500) -> int:
    """Translate a period string like ``'90d'`` into an approximate bar count."""
    try:
        period = period.strip().lower()
        if period.endswith('d'):
            return max(int(period[:-1]) * 24, 50)  # assume hourly bars
        if period.endswith('w'):
            return max(int(period[:-1]) * 24 * 7, 50)
        if period.endswith('h'):
            return max(int(period[:-1]), 50)
        return max(int(period), 50)
    except (ValueError, AttributeError):
        return default


@dataclass
class StrategySignal:
    """Signal generated by a trading strategy"""
    action: str  # 'buy', 'sell', 'hold'
    confidence: float
    price: float
    timestamp: datetime
    indicators: Dict[str, float]
    reasoning: str


class BaseStrategy(ABC):
    """Base class for all trading strategies"""

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.parameters = config.get('parameters', {})
        self.name = self.__class__.__name__

    @abstractmethod
    def generate_signal(self, market_data: Dict[str, Any]) -> Optional[StrategySignal]:
        """Generate trading signal from market data"""
        pass

    @abstractmethod
    def backtest(self, symbol: str, period: str) -> Dict[str, Any]:
        """Backtest the strategy"""
        pass

    def set_parameters(self, parameters: Dict[str, Any]):
        """Update strategy parameters"""
        self.parameters.update(parameters)

    def get_parameters(self) -> Dict[str, Any]:
        """Get current strategy parameters"""
        return self.parameters.copy()


class SuperTrendStrategy(BaseStrategy):
    """
    SuperTrend Indicator Strategy

    Uses ATR-based dynamic support/resistance levels for trend following.
    """

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.atr_period = self.parameters.get('atr_period', 10)
        self.multiplier = self.parameters.get('multiplier', 3.0)

    def generate_signal(self, market_data: Dict[str, Any]) -> Optional[StrategySignal]:
        """Generate SuperTrend signal for the most recent bar.

        Emits a ``buy``/``sell`` only when the trend direction flips on the
        latest bar (a genuine crossover), otherwise ``hold``. The SuperTrend
        line and direction arrays are index-aligned with ``close`` so the signal
        always reflects the current bar (no off-by-one drift).
        """

        try:
            # Extract OHLC data
            high = market_data.get('high', [])
            low = market_data.get('low', [])
            close = market_data.get('close', [])

            if len(close) < self.atr_period + 1:
                logger.warning("Insufficient data for SuperTrend calculation")
                return None

            supertrend, direction, atr = self._calculate_supertrend(high, low, close)

            current_price = close[-1]
            current_st = supertrend[-1]
            current_direction = direction[-1]
            prev_direction = direction[-2] if len(direction) > 1 else current_direction

            indicators = {
                'supertrend': current_st,
                'atr': atr[-1],
                'direction': current_direction,
            }

            if current_direction == 1 and prev_direction == -1:
                return StrategySignal(
                    action='buy',
                    confidence=0.8,
                    price=current_price,
                    timestamp=datetime.now(),
                    indicators=indicators,
                    reasoning=f"Price crossed above SuperTrend line at {current_price:.2f}",
                )

            if current_direction == -1 and prev_direction == 1:
                return StrategySignal(
                    action='sell',
                    confidence=0.8,
                    price=current_price,
                    timestamp=datetime.now(),
                    indicators=indicators,
                    reasoning=f"Price crossed below SuperTrend line at {current_price:.2f}",
                )

            return StrategySignal(
                action='hold',
                confidence=0.5,
                price=current_price,
                timestamp=datetime.now(),
                indicators=indicators,
                reasoning="No trend change detected",
            )

        except Exception as e:
            logger.error(f"Error generating SuperTrend signal: {e}")
            return None

    def _calculate_supertrend(
        self,
        high: List[float],
        low: List[float],
        close: List[float],
    ) -> tuple:
        """Calculate the SuperTrend line, direction and ATR.

        All three returned lists are aligned to ``close`` indices (length n).
        ``direction`` uses 1 for uptrend and -1 for downtrend.
        """
        from utils.indicators import calculate_atr

        n = len(close)
        atr = calculate_atr(high, low, close, self.atr_period)

        hl2 = [(high[i] + low[i]) / 2 for i in range(n)]
        basic_upper = [hl2[i] + self.multiplier * atr[i] for i in range(n)]
        basic_lower = [hl2[i] - self.multiplier * atr[i] for i in range(n)]

        final_upper = [0.0] * n
        final_lower = [0.0] * n
        direction = [1] * n
        supertrend = [0.0] * n

        final_upper[0] = basic_upper[0]
        final_lower[0] = basic_lower[0]
        supertrend[0] = final_lower[0]

        for i in range(1, n):
            # Carry the band forward unless price/band movement allows a reset.
            if basic_upper[i] < final_upper[i - 1] or close[i - 1] > final_upper[i - 1]:
                final_upper[i] = basic_upper[i]
            else:
                final_upper[i] = final_upper[i - 1]

            if basic_lower[i] > final_lower[i - 1] or close[i - 1] < final_lower[i - 1]:
                final_lower[i] = basic_lower[i]
            else:
                final_lower[i] = final_lower[i - 1]

            prev_dir = direction[i - 1]
            if prev_dir == 1:
                direction[i] = -1 if close[i] < final_lower[i] else 1
            else:
                direction[i] = 1 if close[i] > final_upper[i] else -1

            supertrend[i] = final_lower[i] if direction[i] == 1 else final_upper[i]

        return supertrend, direction, atr

    def backtest(self, symbol: str, period: str) -> Dict[str, Any]:
        """Backtest the SuperTrend strategy on historical/market data.

        Uses the event-driven :class:`~utils.backtest.Backtester` with the
        strategy's configured risk parameters. Falls back gracefully if data is
        unavailable.
        """
        return _run_backtest(self, symbol, period, self.config)


